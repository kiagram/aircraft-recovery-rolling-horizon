"""Column-generation results -> paper/tables/tab_cg.tex, tab_cg_us.tex, paper/figs/fig_cg_conv.{pdf,png}.
   python analysis_cg.py [out_dir]       (reads results_cg/*v4.json, results_cg/B01__cg-coarse-ipm.json, results_us2014/*__cg-*.json,
   results_cg/master_sizes.json and, for the B01 flow-LP reference, results/B01__fh-coarse-2h.json -- read-only)."""
import json
import os
import sys

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "paper")
CG, US, RES = (os.path.abspath(sys.argv[i]) if len(sys.argv) > i else os.path.join(HERE, d)
               for i, d in ((2, "results_cg"), (3, "results_us2014"), (4, "results")))
os.makedirs(os.path.join(OUT, "tables"), exist_ok=True)
os.makedirs(os.path.join(OUT, "figs"), exist_ok=True)
J = lambda p: json.load(open(p))
SIZES = J(os.path.join(CG, "master_sizes.json")) if os.path.exists(os.path.join(CG, "master_sizes.json")) else {}
V2 = not os.path.exists(os.path.join(CG, "A01__cg-fine-v4.json"))       # Stage-2 reruns: plain tags
US_INST = ["US03", "US08_EMB120", "US02_CRJ700", "US08_CRJ700", "US02_A320", "US08_A320", "US02_B737", "US02_CRJ200"]


def fmt(x, nd=0):
    return "--" if x is None else f"{x:,.{nd}f}"


def runs():
    """(label, record, FH-LP reference, size key v3, size key v4)"""
    fh2 = J(os.path.join(RES, "B01__fh-coarse-4h.json" if os.path.exists(os.path.join(RES, "B01__fh-coarse-4h.json"))
                         else "B01__fh-coarse-2h.json"))
    # LP bound of the coarse-grid flow model (2 h FH run); Stage-2 results: only if that LP is certified Optimal (R-8)
    b01_fhlp = fh2["bound"] if "certificate" not in fh2 or fh2["certificate"].get("bound_source") == "LP optimal" else None
    v = "" if V2 else "-v4"
    r = []
    for n, g in (("A01", "fine"), ("A02", "fine")):
        d = J(os.path.join(CG, f"{n}__cg-{g}{v}.json"))
        r.append((f"{n} (fine)", d, d["fh_lp_bound"], None if V2 else f"{n}__cg-{g}-v3", f"{n}__cg-{g}{v}"))
    for tag, lab in ((f"B01__cg-coarse{v}", "B01 (coarse), simplex"), ("B01__cg-coarse-ipm", "B01 (coarse), IPM duals")):
        if os.path.exists(os.path.join(CG, tag + ".json")):
            d = J(os.path.join(CG, tag + ".json"))
            r.append((lab, d, b01_fhlp, None if (V2 or "ipm" in tag) else "B01__cg-coarse-v3", tag))
    d = J(os.path.join(US, "US02_B737__cg-coarse.json"))
    r.append(("US02\\_B737 (coarse)", d, d["fh_lp_bound"] or fh_bound(US, "US02_B737"), None, "US02_B737__cg-coarse"))
    return r


def fh_bound(folder, n):
    """certified LP value of the FH run (flow model, same copies) if its LP was solved to optimality"""
    for x in os.listdir(folder):
        if x.startswith(n + "__fh-"):
            r = J(os.path.join(folder, x))
            if "certificate" not in r or r["certificate"].get("bound_source") == "LP optimal":
                return r["bound"]
    return None


def table():
    rows = []
    for lab, d, fhlp, k3, k4 in runs():
        cg = d["cg"]
        s4 = SIZES[k4]["rows"] if k4 in SIZES else d.get("master_rows")
        sz = f"{SIZES[k3]['rows']:,} $\\to$ {s4:,}" if k3 else ("--" if s4 is None else f"{s4:,}")
        lagr = cg["lagr_lb"]
        rows.append(dict(lab=lab, size=sz, it=cg["iterations"], t=cg["time"], lp_share=100 * cg["lp_time"] / cg["time"],
                         pr_share=100 * cg["pricing_time"] / cg["time"], lp=cg["lp_obj"], fhlp=fhlp,
                         ratio=cg["lp_obj"] / fhlp if fhlp else None,
                         lagr=lagr, status=cg["status"], ub=d["ub"], viol=d["eval"]["n_violations"],
                         mip=d["mip"]["status"], mip_t=d["mip"]["time"], rmp=d.get("rmp_lp", "simplex")))
    json.dump(rows, open(os.path.join(CG, "summary_cg.json"), "w"), indent=1, default=str)
    with open(os.path.join(OUT, "tables", "tab_cg.tex"), "w") as f:
        f.write("% generated by arp_rh/analysis_cg.py; model objectives (not evaluator totals); FH LP = LP of the flow model\n")
        f.write("\\begin{tabular}{lrrrrrrrrr}\\toprule\n")
        f.write("Instance & Master rows & Iter. & CG time (s) & LP share (\\%) & RMP LP & FH LP & RMP/FH & Lagr. bound & Viol.\\\\\\midrule\n")
        for r in rows:
            lagr = r["lp"] if r["status"] == "converged" else r["lagr"]
            f.write(" & ".join([r["lab"], r["size"], str(r["it"]), fmt(r["t"]), fmt(r["lp_share"]), fmt(r["lp"]), fmt(r["fhlp"]),
                                "--" if r["ratio"] is None else f"{r['ratio']:.3f}", fmt(lagr) + ("" if r["status"] == "converged" else "$^\\dagger$"), str(r["viol"])]) + "\\\\\n")
        f.write("\\bottomrule\\end{tabular}\n")
    # appendix: all eight US instances
    occ = {}
    out = []
    for n in US_INST:
        d = [x for x in os.listdir(US) if x.startswith(n + "__cg-")][0]
        cg = J(os.path.join(US, d))
        o = J(os.path.join(US, f"{n}__occ.json"))["eval"]["total"]
        fh = J([os.path.join(US, x) for x in os.listdir(US) if x.startswith(n + "__fh-")][0])
        if not cg.get("fh_lp_bound"):
            cg["fh_lp_bound"] = fh_bound(US, n)      # certified flow-LP value of the FH run (same model and copies)
        out.append(dict(n=n, grid=cg["grid"], cg_t=cg["runtime"], cg_cg_t=cg["cg"]["time"], it=cg["cg"]["iterations"],
                        rmp_over_fh=cg["lp_bound"] / cg["fh_lp_bound"] if cg.get("fh_lp_bound") else None,
                        lagr=cg["cg"]["lagr_lb"], ub=cg["ub"], ev=cg["eval"]["total"], occ=o, vs_occ=100 * (cg["eval"]["total"] / o - 1),
                        viol=cg["eval"]["n_violations"], mip=cg["mip"]["status"], mip_t=cg["mip"]["time"],
                        cg_status=cg["cg"]["status"]))
    json.dump(out, open(os.path.join(CG, "summary_cg_us.json"), "w"), indent=1, default=str)
    with open(os.path.join(OUT, "tables", "tab_cg_us.tex"), "w") as f:
        f.write("% generated by arp_rh/analysis_cg.py; CG plan evaluated by the independent evaluator, relative to the OCC plan\n")
        f.write("\\begin{tabular}{lrrrrrrr}\\toprule\n")
        f.write("Inst. & Grid & Iter. & CG stop (s) & RMP LP / FH LP & Lagr. bound & CG plan vs OCC (\\%) & MIP time (s)\\\\\\midrule\n")
        for r in out:
            f.write(" & ".join([r["n"].replace("_", "\\_"), r["grid"], str(r["it"]), fmt(r["cg_cg_t"]), ("--" if r["rmp_over_fh"] is None else f"{r['rmp_over_fh']:.2f}"),
                                fmt(r["lagr"]), f"{r['vs_occ']:+.1f}", fmt(r["mip_t"])]) + "\\\\\n")
        f.write("\\bottomrule\\end{tabular}\n")
    return rows


def figure(rows):
    C = {"A01 (fine)": ("#2a78d6", "o"), "A02 (fine)": ("#1baf7a", "s"), "B01 (coarse), simplex": ("#eb6834", "^"),
         "B01 (coarse), IPM duals": ("#eda100", "D"), "US02\\_B737 (coarse)": ("#52514e", "v")}
    fig, ax = plt.subplots(figsize=(5.8, 3.4))
    for lab, d, fhlp, _, _ in runs():
        c, m = C[lab]
        xs = [h[1] for h in d["hist"]]
        if not fhlp:
            continue
        ys = [max(100 * (h[2] / fhlp - 1), 1e-4) for h in d["hist"]]
        ax.plot(xs, ys, color=c, marker=m, ms=3.5, lw=1.2, label=lab.replace("\\_", "_"))
    ax.set_xscale("log"); ax.set_yscale("log")
    ax.set_xlabel("CG time (s)"); ax.set_ylabel("RMP value above flow-LP bound (%)")
    ax.legend(frameon=False, fontsize=7)
    ax.grid(True, color="#e4e3df", lw=0.6)
    fig.tight_layout()
    for ext in ("pdf", "png"):
        fig.savefig(os.path.join(OUT, "figs", f"fig_cg_conv.{ext}"), dpi=200)


if __name__ == "__main__":
    figure(table())
    for r in json.load(open(os.path.join(CG, "summary_cg.json"))):
        print({k: (round(v, 3) if isinstance(v, float) else v) for k, v in r.items()})
