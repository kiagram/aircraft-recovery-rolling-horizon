"""Cross-benchmark synthesis -> paper/tables/tab_synth.tex, results_us2014/synth_us2014_roadef.json.
   Mean cost gap (%) of each policy to the FH plan on (i) the ten one-day ROADEF A-type instances, (ii) the six B/XB instances
   where FH is the best known solution (B01, B03, B04 with the 2 h run; B09, XB01, XB03), (iii) the eight US2014-R scale-down
   instances.  Violations = total number of violated maintenance/other requirements over the group.
   R-5: every method of an instance on the instance's grid (D6, arp.reporting.grid_of); means over feasible plans only,
   infeasible plans counted separately; an infeasible FH reference is reported and the instance skipped."""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "paper")
R = os.path.abspath(sys.argv[2]) if len(sys.argv) > 2 else os.path.join(HERE, "results")
U = os.path.abspath(sys.argv[3]) if len(sys.argv) > 3 else os.path.join(HERE, "results_us2014")
A1 = ["A01", "A02", "A03", "A04", "A06", "A07", "A08", "A09", "XA01", "XA03"]
BF = ["B01", "B03", "B04", "B09", "XB01", "XB03"]
US = ["US03", "US08_EMB120", "US02_CRJ700", "US08_CRJ700", "US02_A320", "US08_A320", "US02_B737", "US02_CRJ200"]
sys.path.insert(0, HERE)
from arp import reporting as rp   # noqa: E402
POL = [("OCC", "occ"), ("STG-60", "rh-60-60-stage-none-static-{g}"), ("RH-M 60/60", "rh-60-60-exec-none-static-{g}"),
       ("RH-T 60/60", "rh-60-60-exec-boundary[kms]-static-{g}"), ("RH-T 60/180", "rh-60-180-exec-boundary[kms]-static-{g}"),
       ("RH-T 60/360", "rh-60-360-exec-boundary[kms]-static-{g}")]


def rec(d, n, tag):
    p = os.path.join(d, f"{n}__{tag}.json")
    return json.load(open(p)) if os.path.exists(p) else None


def group(d, insts, fh_tags):
    out = {}
    for lab, pat in POL:
        gaps, viol, cnt, n_inf = [], 0, 0, 0
        for n in insts:
            fh = rp.best(r for r in (rec(d, n, t) for t in fh_tags(n)) if r)
            r = rec(d, n, pat.format(g=rp.grid_of(n)))
            if r is None or fh is None:
                continue
            if not rp.feasible(fh):
                print("infeasible FH reference skipped:", n, rp.hard_violations(fh))
                continue
            if not rp.feasible(r):
                n_inf += 1
                continue
            gaps.append(100 * (r["eval"]["total"] / fh["eval"]["total"] - 1)); viol += r["eval"]["n_violations"]; cnt += 1
        out[lab] = (sum(gaps) / len(gaps) if gaps else None, viol, cnt, n_inf)
    return out


def fh_best_known(d, insts):
    """B/XB instances whose best feasible plan (any method, instance grid, R-5 rule) is the FH plan"""
    import glob as _g
    out = []
    for n in insts:
        recs = [json.load(open(f)) for f in _g.glob(os.path.join(d, f"{n}__*.json"))]
        by = rp.group([r for r in recs if isinstance(r, dict) and "eval" in r and "policy" in r])
        ref = rp.reference(by.get(n, {}))
        if ref is not None and ref["policy"].startswith("fh") and rp.feasible(ref):
            out.append(n)
    return out


BALL = [f"B{i:02d}" for i in range(1, 11)] + [f"XB{i:02d}" for i in range(1, 5)]
BF = fh_best_known(R, BALL) if len(sys.argv) > 2 else BF
print("B/XB instances with FH best known:", BF)
G = {"A": group(R, A1, lambda n: ["fh-fine"]),
     "B": group(R, BF, lambda n: ["fh-coarse-4h", "fh-coarse-2h", "fh-coarse"]),
     "US": group(U, US, lambda n: ["fh-" + rp.grid_of(n)])}
json.dump(G, open(os.path.join(U, "synth_us2014_roadef.json"), "w"), indent=1)
with open(os.path.join(OUT, "tables", "tab_synth.tex"), "w") as f:
    f.write("% generated by arp_rh/analysis_synth.py\n\\begin{tabular}{lrrrrrr}\\toprule\n")
    f.write(" & \\multicolumn{2}{c}{ROADEF A, one day (10)} & \\multicolumn{2}{c}{ROADEF B/XB, FH best known (" + str(len(BF))
            + ")} & \\multicolumn{2}{c}{US2014-R (8)}\\\\\n")
    f.write("Policy & Gap (\\%) & Viol. & Gap (\\%) & Viol. & Gap (\\%) & Viol.\\\\\\midrule\n")
    for lab, _ in POL:
        cells = [lab]
        for k in ("A", "B", "US"):
            g, v, c, ni = G[k][lab]
            cells += ["--", "--"] if g is None else [f"{g:.1f}" + (f"$^{{\\dagger {ni}}}$" if ni else ""), str(v)]
        f.write(" & ".join(cells) + "\\\\\n")
    f.write("\\bottomrule\\end{tabular}\n")
print(open(os.path.join(OUT, "tables", "tab_synth.tex")).read())
